"""Which files this request has already looked at.

OpenCode refuses to write over *any* file the session has not read, which is the
right rule for an agent whose whole job is editing an existing codebase. Here it
would be mostly friction: this agent's normal act is producing a new artifact in
the chat folder and then rewriting it, and making it re-read its own draft each
time costs a round trip and a context window to prevent nothing.

The case that is *not* friction is ``uploads/``. Those are the user's files,
attached through the @-menu, and they are the only files in the sandbox that
existed before the agent did and cannot be regenerated by it. A blind full
overwrite there destroys the original — and "blind" is the operative word, since
a model that has read the file is by definition able to preserve what matters.

So the ledger records reads, and only an unread *upload* is refused. Its lifetime
is one request, like the sandbox policy it sits beside: the two flows this
protects (read-then-rewrite, edit-my-attachment) both happen inside one turn, and
the refusal names the fix, so a model that hits it recovers in one extra call.
"""

from __future__ import annotations

from dataclasses import dataclass, field

# Both are the canonical implementations of exactly what is needed here, and
# both are already imported across module lines elsewhere in the app.
from agent.sandbox import _normalize
from agent.untrusted import _reads_upload


@dataclass
class ReadLedger:
    """The set of paths read during one request."""

    _seen: set[str] = field(default_factory=set)

    def record(self, path: str) -> None:
        """Note that *path* was read."""
        if path:
            self._seen.add(_normalize(path))

    def was_read(self, path: str) -> bool:
        return _normalize(path) in self._seen

    def refuse_blind_overwrite(self, path: str) -> str | None:
        """Why *path* must be read before being replaced wholesale, or None.

        Callers apply this only where the whole file is being replaced. A
        targeted edit carries its own evidence: the model had to quote the
        existing text to name what it was replacing.
        """
        if not _reads_upload(path) or self.was_read(path):
            return None
        return (
            f"Error: {path} is a file the user attached, and you have not read it. "
            "Overwriting it would discard their original. Read it first "
            "(read_file), then write — or use edit_file to change just the part "
            "you mean to change."
        )
